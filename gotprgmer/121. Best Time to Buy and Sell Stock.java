class Solution {
    public int maxProfit(int[] prices) {
        /*
         * [문제 정의]
         * - 주식을 한 번 사고 한 번 팔아 얻을 수 있는 최대 이익을 구한다.
         * - 매수는 반드시 매도보다 먼저 이루어져야 한다.
         * - 이익을 얻을 수 없다면 0을 반환한다.
         *
         * [초기 접근: 완전탐색]
         * - 첫 번째 반복문에서 매수 시점을 선택한다.
         * - 두 번째 반복문에서 매수 이후의 매도 시점을 탐색한다.
         * - 모든 매수·매도 조합의 이익을 비교한다.
         *
         * [병목 분석]
         * - 시간복잡도 O(N²)
         * - N <= 10^5이므로 시간 초과가 발생할 수 있다.
         * - 서로 다른 매수 시점에서 동일한 매도 후보를 반복 탐색한다.
         *
         * [최적화 전략: 중복 계산 제거]
         * - 매수 시점마다 모든 매도 후보를 확인할 필요가 있는가?
         * - 각 매수 시점 이후의 최고 주가만 알면 최대 이익을 계산할 수 있다.
         *
         * 1. 뒤에서부터 순회하며 각 시점 이후의 최고 주가를 저장한다.
         *    dp[i] = max(prices[i], dp[i+1])
         *
         * 2. 각 매수 시점에서 미래의 최고 주가와 차이를 계산한다.
         *    profit = dp[i+1] - prices[i]
         *
         * 3. 계산한 이익 중 최댓값을 반환한다.
         *
         * [복잡도]
         * - 시간복잡도 O(N): 배열을 두 번 순회한다.
         * - 공간복잡도 O(N): 미래 최고 주가를 저장하는 DP 배열을 사용한다.
         */

        // 각 시점부터 마지막 날까지의 최고 주가 계산
        int[] dp = new int[prices.length];
        dp[dp.length - 1] = prices[dp.length - 1];

        for (int i = dp.length - 2; i >= 0; i--) {
            dp[i] = Math.max(prices[i], dp[i + 1]);
        }

        // 각 매수 시점에서 얻을 수 있는 최대 이익 계산
        int diff = Integer.MIN_VALUE;

        for (int i = 0; i < prices.length - 1; i++) {
            diff = Math.max(dp[i + 1] - prices[i], diff);
        }

        // 이익을 얻을 수 없다면 0 반환
        if (diff < 0) {
            return 0;
        }

        return diff;
    }
}